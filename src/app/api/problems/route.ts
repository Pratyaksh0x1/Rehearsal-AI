import { NextRequest, NextResponse } from 'next/server';
import { requireUser } from '@/lib/supabase/server';
import {
  getNextProblemForCandidate,
  getCandidateProblemHistory,
  getCandidateStats,
  getProblemsByTier,
  getAllProblems,
} from '@/lib/problems/history';
import { saveProblemSession } from '@/lib/problems/session';
import { generateInterviewProblem } from '@/lib/problems/generator';

export const dynamic = 'force-dynamic';

export async function GET(req: NextRequest) {
  try {
    const { user: authUser, error: authError } = await requireUser();
    if (authError || !authUser) {
      return NextResponse.json(
        { error: 'Unauthorized: login required' },
        { status: 401 }
      );
    }

    const { searchParams } = new URL(req.url);
    const tier = searchParams.get('tier') || 'Bronze';
    const mode = searchParams.get('mode'); // 'next' | 'history' | 'stats' | null
    const difficulty = searchParams.get('difficulty');
    const company = searchParams.get('company');
    const userId = authUser.id;

    // 1. Next Problem for this candidate: dynamically generated by LLM matching player rank & company
    if (mode === 'next') {
      try {
        const genResult = await generateInterviewProblem({
          rankTier: tier,
          company: company && company !== 'Any company' ? company : null,
        });
        return NextResponse.json(genResult);
      } catch (err: any) {
        console.warn('Dynamic LLM problem generation failed, falling back to database:', err?.message || err);
        const nextResult = await getNextProblemForCandidate({
          userId,
          rankTier: tier,
          difficulty,
          company,
        });

        if (nextResult?.problem) {
          const fullProblem = nextResult.problem;
          const problemSessionId = saveProblemSession(fullProblem);

          const safeProblem = {
            ...fullProblem,
            test_cases: fullProblem.test_cases
              ? fullProblem.test_cases.filter((t: any) => !t.is_hidden)
              : [],
          };
          delete (safeProblem as any).solution_approach;
          delete (safeProblem as any).optimal_complexity;
          delete (safeProblem as any).hints;

          return NextResponse.json({
            ...nextResult,
            problem: safeProblem,
            problemSessionId,
          });
        }

        return NextResponse.json(nextResult);
      }
    }

    // 2. Full Attempt History for candidate
    if (mode === 'history') {
      if (!userId) {
        return NextResponse.json({ history: [], message: 'No candidate userId provided' });
      }
      const history = await getCandidateProblemHistory(userId);
      return NextResponse.json({ history });
    }

    // 3. Aggregate Stats for candidate
    if (mode === 'stats') {
      if (!userId) {
        return NextResponse.json({
          stats: { totalAttempts: 0, totalSolved: 0, unsolvedCount: 0 },
        });
      }
      const stats = await getCandidateStats(userId);
      return NextResponse.json({ stats });
    }

    // 4. Default: Problem list for the tier
    const problems = tier ? await getProblemsByTier(tier) : await getAllProblems();
    return NextResponse.json({ problems, total: problems.length });
  } catch (error: any) {
    console.error('Problems API error:', error);
    return NextResponse.json(
      { error: error?.message || 'Failed to process problems request' },
      { status: 500 }
    );
  }
}
